const HTML_ENTITIES: Record<string, string> = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
const FIVEM_CONTROL_BIT = 0x80000000;

export interface BoundKey {
    text: string | null;
    icon: string | null;
}

export function controlIndexOf(name: string): number | null {
    return CONTROL_INDEXES.get(name) ?? null;
}

export function decodeHtmlEntities(text: string): string {
    return text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (match, entity: string) => {
        if (entity[0] === '#') {
            const code = entity[1] === 'x' || entity[1] === 'X' ? parseInt(entity.slice(2), 16) : Number(entity.slice(1));
            return Number.isFinite(code) ? String.fromCodePoint(code) : match;
        }
        return HTML_ENTITIES[entity.toLowerCase()] ?? match;
    });
}

export function stripMarkup(text: string): string {
    return decodeHtmlEntities(text.replace(/<[^>]*>/g, '').replace(/~[a-zA-Z0-9_]+~/g, '')).trim();
}

export function buttonLabel(button: string): string | null {
    const kind = button.slice(0, 2);
    const value = button.slice(2).trim();
    if (value.length === 0) return null;
    if (kind === 't_' || kind === 'T_') return decodeHtmlEntities(value).toUpperCase();
    if (kind === 'b_' && /^\d+$/.test(value)) return KEY_ICON_NAMES[Number(value)] ?? null;
    return null;
}

export function controlOfToken(token: string): number | null {
    const name = /^~INPUT_(\w+)~$/.exec(token)?.[1];
    if (!name) return null;
    const index = controlIndexOf(name);
    if (index !== null) return index;
    return /^[0-9A-F]{8}$/.test(name) ? (parseInt(name, 16) | FIVEM_CONTROL_BIT) >> 0 : null;
}

export function resolveBoundKey(raw: string | null, token: string, slot: number): BoundKey {
    if (!raw || raw === '|' || token === '') return { text: null, icon: null };
    if (raw.startsWith('t|')) return { text: decodeHtmlEntities(raw.slice(2)), icon: null };

    const control = slot === 0 ? controlOfToken(token) : null;
    if (control !== null) {
        const label = buttonLabel(GetControlInstructionalButton(0, control, true) ?? '');
        if (label) return { text: label, icon: null };
    }
    return { text: null, icon: '?' };
}
